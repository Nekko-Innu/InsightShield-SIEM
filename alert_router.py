# alert_router.py
# Insight Shield — Severity Routing + After-Hours Escalation
# Purpose : Central routing logic. Apply after-hours escalation FIRST,
#           then route to notification channels based on severity.
#           Escalation logic lives ONLY here — never in notifier.py or
#           wazuh_receiver.py.
# Used by : wazuh_receiver.process_alert()

import logging
from datetime import datetime, timedelta

import config
import _request_cache

logger = logging.getLogger("insightshield.alert_router")


def dispatch_internal_alert(
    attack_type: str,
    rule_id: str,
    source_ip: str | None,
    plain_text: str,
    evidence: dict,
    severity: str = "HIGH",
    dedupe_minutes: int = 60,
) -> int | None:
    """
    Raise an alert Insight Shield generated about its own traffic, and route it.

    Lifted out of web/blueprints/auth.py, where it existed as
    _maybe_dispatch_brute_force_alert with every string hard-coded. The
    authorization-probe sweep needs the identical sequence — dedupe, store,
    route, audit — and a second copy of seventy lines is how the two drift.

    Idempotent per (attack_type, source_ip) within `dedupe_minutes`, checked
    against the ALERT_DISPATCHED audit row this function writes. Without that,
    a sustained campaign re-fires Telegram and email on every sweep, which is
    the alert-fatigue failure A09 warns about.

    Returns the new alert id, or None if suppressed or if dispatch failed —
    callers are fire-and-forget and must not raise into a request or a job.
    """
    import json

    import db

    if not source_ip:
        return None

    target = f"{attack_type}:{source_ip}"
    cutoff = (
        datetime.now(tz=config.PHT) - timedelta(minutes=dedupe_minutes)
    ).isoformat()
    try:
        prior = db._get_conn().execute(
            "SELECT 1 FROM audit_log "
            "WHERE action = 'ALERT_DISPATCHED' AND target = ? AND ts > ? LIMIT 1",
            (target, cutoff),
        ).fetchone()
        if prior:
            return None
    except Exception as e:
        # Fall through and dispatch — better to occasionally double-notify than
        # to silently drop a real escalation because a bookkeeping query failed.
        logger.warning("%s idempotency check failed: %s", attack_type, e)

    now = datetime.now(tz=config.PHT).isoformat()
    raw_alert = json.dumps({
        "rule": {"id": rule_id, "level": 11,
                 "description": f"{attack_type} (Insight Shield internal)"},
        "agent": {"ip": source_ip, "name": "insightshield"},
        "data": {"srcip": source_ip, **evidence},
        "full_log": plain_text,
        "timestamp": now,
    }, ensure_ascii=False)
    alert_dict = {
        "timestamp":     now,
        "rule_id":       rule_id,
        "attack_type":   attack_type,
        "severity":      severity,
        "device_name":   source_ip,
        "raw_alert":     raw_alert,
        "plain_text":    plain_text,
        "ai_reasoning":  "Internal — generated by Insight Shield, not by an AI provider",
        "provider_used": "internal",
        "fk_grade":      None,
        "attack_trail":  raw_alert,
    }
    try:
        alert_id = db.store_alert(alert_dict)
        alert_dict["id"] = alert_id
        route_alert(severity, alert_dict)
        detail = " ".join(f"{k}={v}" for k, v in evidence.items())
        db.log_audit(
            action="ALERT_DISPATCHED",
            actor="system",
            target=target,
            ip=source_ip,
            details=f"alert_id={alert_id} {detail}".strip(),
        )
        logger.warning("%s alert dispatched: ip=%s alert_id=%d %s",
                       attack_type, source_ip, alert_id, detail)
        return alert_id
    except Exception as e:
        logger.error("Failed to dispatch %s alert: %s", attack_type, e)
        return None


def route_alert(severity: str, alert: dict) -> None:
    """
    Apply after-hours escalation, then route to notification channels.

    Channel matrix:
      INFO/LOW   → dashboard only
      MEDIUM     → IT Telegram only (suppressed if same rule_id within 10 min)
      HIGH       → IT Telegram + Manager Telegram (+ IT Email if EMAIL_ENABLED),
                   once per rule + device per NOTIFY_COOLDOWN_MIN
      CRITICAL   → same as HIGH + the 5-minute escalation sweep, which pages
                   every unacknowledged CRITICAL — cooled-down ones included

    Parameters
    ----------
    severity : str
        Original severity: INFORMATIONAL, LOW, MEDIUM, HIGH, CRITICAL.
    alert : dict
        Full alert dict from db.get_alert() (all 20 columns).
    """
    # Import here to avoid circular imports (notifier imports config,
    # but alert_router is called from wazuh_receiver which also imports config)
    import notifier
    import rate_limit
    import scheduler

    original_severity = severity

    # Step 1: After-hours escalation
    if is_outside_hours():
        severity = escalate_one_tier(severity)
        if severity != original_severity:
            logger.info(
                "After-hours escalation: %s → %s for alert_id=%s",
                original_severity, severity, alert.get("id"),
            )

    # Step 2: Route by severity
    if severity in ("INFORMATIONAL", "LOW"):
        logger.info("Alert id=%s severity=%s: dashboard only", alert.get("id"), severity)
        return

    if severity == "MEDIUM":
        # Flood suppression: 1 Medium Telegram per rule_id per 10 min.
        rule_id = str(alert.get("rule_id") or "")
        allowed, retry_after = rate_limit.can_call(
            f"tg-medium:{rule_id}", limit_per_min=1, window_seconds=600,
        )
        if allowed:
            notifier.send_telegram(alert)
        else:
            logger.info(
                "Medium Telegram suppressed: rule_id=%s retry_after=%.0fs",
                rule_id, retry_after,
            )

    elif severity in ("HIGH", "CRITICAL"):
        # Cooldown per rule on one device. Without it an ARP spoof, which
        # re-poisons every 2 s, sent three messages per stored row — sixty rows
        # in thirty seconds. Keyed on the device too, so the same attack
        # landing on a second machine still notifies. Suppressed alerts are
        # still stored, shown, and (if CRITICAL) included in the escalation
        # sweep's digest, so nothing is lost but the duplicate message.
        key = f"notify:{alert.get('rule_id')}:{alert.get('device_name')}"
        allowed, retry_after = rate_limit.can_call(
            key, limit_per_min=1, window_seconds=config.NOTIFY_COOLDOWN_MIN * 60,
        )
        if not allowed:
            logger.info(
                "Notification suppressed (cooldown): alert_id=%s %s retry_after=%.0fs",
                alert.get("id"), key, retry_after,
            )
            return
        notifier.send_telegram(alert)
        notifier.send_email(alert)
        notifier.send_manager_telegram(alert)

        # CRITICAL escalation needs no registration: scheduler._escalation_sweep
        # finds unacknowledged CRITICALs by querying the alerts table. Storing
        # the row IS enrolling it.

    logger.info(
        "Alert routed: id=%s severity=%s (original=%s) channels=%s",
        alert.get("id"), severity, original_severity,
        _channels_for(severity),
    )


def is_outside_hours() -> bool:
    """
    Check if current Philippine time is outside business hours.
    Returns True if before 08:00 or at/after 21:00 PHT.
    """
    hour = datetime.now(tz=config.PHT).hour
    return hour < config.BUSINESS_START or hour >= config.BUSINESS_END


def escalate_one_tier(severity: str) -> str:
    """
    Promote severity one level for after-hours alerts.
    MEDIUM → HIGH, HIGH → CRITICAL.
    INFORMATIONAL, LOW, CRITICAL: unchanged (no double-escalation).
    """
    escalation = {
        "MEDIUM": "HIGH",
        "HIGH": "CRITICAL",
    }
    return escalation.get(severity, severity)


def _channels_for(severity: str) -> str:
    """Return a human-readable string of notification channels for logging."""
    email = "+Email" if config.EMAIL_ENABLED else ""
    channels = {
        "INFORMATIONAL": "dashboard",
        "LOW": "dashboard",
        "MEDIUM": "IT-Telegram(dedup)",
        "HIGH": f"IT-Telegram{email}+Manager-Telegram",
        "CRITICAL": f"IT-Telegram{email}+Manager-Telegram+Escalation",
    }
    return channels.get(severity, "unknown")
